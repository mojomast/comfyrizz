/**
 * Build-time asset step (A5 + A1): sanitize and CPU render-check every `llm-svg`
 * asset in the bundled example, then emit `src/generated-assets.ts` so the
 * composition inlines already-verified markup. No network, no clocks.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const rendererDir = join(here, '..');
const repoRoot = join(rendererDir, '..', '..');
const exampleDir = join(repoRoot, 'examples', 'launch-demo');
const vectorDir = join(repoRoot, 'packages', 'vector');

const build = spawnSync('npm', ['run', 'build'], { cwd: vectorDir, stdio: 'pipe', encoding: 'utf8' });
if (build.status !== 0) {
  process.stderr.write(build.stdout ?? '');
  process.stderr.write(build.stderr ?? '');
  throw new Error('packages/vector build failed');
}

const { sanitizeSvg, renderCheck, SANITIZER_VERSION } = await import(join(vectorDir, 'dist', 'src', 'index.js'));
const pkg = JSON.parse(readFileSync(join(exampleDir, 'package.json'), 'utf8'));
const palette = pkg.theme?.palette;
const entries = [];

for (const [id, asset] of Object.entries(pkg.assets ?? {})) {
  if (asset.gen?.generator !== 'llm-svg') continue;
  const file = join(exampleDir, asset.file);
  const raw = readFileSync(file, 'utf8');
  const sha256 = createHash('sha256').update(raw).digest('hex');
  const bytes = Buffer.byteLength(raw);
  if (asset.sha256 !== sha256) throw new Error(`${id}: package sha256 ${asset.sha256} != file ${sha256}`);
  if (asset.bytes !== bytes) throw new Error(`${id}: package bytes ${asset.bytes} != file ${bytes}`);

  const sanitized = sanitizeSvg(raw);
  if (!sanitized.ok) throw new Error(`${id}: sanitize failed: ${sanitized.errors.map(error => error.code).join(', ')}`);
  const check = renderCheck(sanitized.svg, { width: 512, palette });
  if (!check.ok) throw new Error(`${id}: render-check failed: ${check.errors.map(error => error.code).join(', ')}`);

  entries.push({
    id,
    file: asset.file,
    kind: asset.kind,
    sha256,
    bytes,
    sanitizerVersion: SANITIZER_VERSION,
    width: check.width,
    height: check.height,
    opaqueFraction: check.opaqueFraction,
    outOfPaletteFraction: check.outOfPaletteFraction,
    svg: sanitized.svg,
  });
  process.stdout.write(`checked ${id}: ${asset.file} ${check.width}x${check.height} opaque=${(check.opaqueFraction * 100).toFixed(1)}%\n`);
}

if (entries.length < 4) throw new Error(`expected at least 4 llm-svg assets, found ${entries.length}`);

// Sanity fence: the example's asset files and the directory listing must agree.
const onDisk = readdirSync(join(exampleDir, 'assets')).filter(name => name.endsWith('.svg')).sort();
const declared = entries.map(entry => entry.file.replace(/^assets\//, '')).sort();
if (onDisk.join(',') !== declared.join(',')) {
  throw new Error(`asset files on disk (${onDisk}) do not match package asset entries (${declared})`);
}

const banner = `// GENERATED by apps/renderer/scripts/build-assets.mjs — do not edit by hand.\n// Sanitizer version: ${SANITIZER_VERSION}. Source: examples/launch-demo/package.json.\n`;
const body = `${banner}\nexport interface GeneratedAsset {\n  id: string;\n  file: string;\n  kind: string;\n  sha256: string;\n  bytes: number;\n  sanitizerVersion: string;\n  width: number;\n  height: number;\n  opaqueFraction: number;\n  outOfPaletteFraction: number | null;\n  svg: string;\n}\n\nexport const GENERATED_ASSETS: Record<string, GeneratedAsset> = ${JSON.stringify(
  Object.fromEntries(entries.map(entry => [entry.id, entry])),
  null,
  2,
)};\n`;

writeFileSync(join(rendererDir, 'src', 'generated-assets.ts'), body);
process.stdout.write(`wrote ${relative(repoRoot, join(rendererDir, 'src', 'generated-assets.ts'))} (${entries.length} assets)\n`);
