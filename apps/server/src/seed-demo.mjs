/**
 * PN05: seed the "Pip's Night Shift" demo into a fresh runtime.
 *
 * The module is deliberately small and side-effect free at import time. It
 * accepts the runtime directory, the example directory and an fs-like object,
 * so tests can point it at a temporary directory and observe every write.
 *
 * Seeding follows one rule: a destination is written only when it does not
 * exist. That covers the package, the generated media, the takes and editor
 * sidecars, and the reference library, so a second run is a no-op and owner
 * edits are never overwritten.
 *
 * Placeholder media and music are generated by the PN02/PN18 scripts. This
 * module only asks those pure generators for a file that is missing from the
 * example directory, then copies what exists into the runtime. No network,
 * model, GPU or browser is involved.
 */

import { createHash } from 'node:crypto';
import * as nodeFs from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

import { validatePackage } from '../../../packages/schema/src/index.mjs';
import { MEDIA, renderClipSvg, renderStill } from '../../../scripts/pip-night-shift/make-media.mjs';
import { TRACKS, renderTrack } from '../../../scripts/pip-night-shift/make-music.mjs';

/** The conversation id the seeded reference library belongs to. */
export const DEMO_CHAT_ID = 'chat_pipnightshift01';

const PACKAGE_ID_RE = /^[A-Za-z0-9_.-]+$/;
const CHAT_ID_RE = /^chat_[A-Za-z0-9_-]{8,80}$/;
const MIME_BY_EXT = Object.freeze({
  png: 'image/png',
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  webp: 'image/webp',
  gif: 'image/gif',
  svg: 'image/svg+xml',
  mp4: 'video/mp4',
  mov: 'video/quicktime',
  webm: 'video/webm',
});

function toPath(value, name) {
  if (value instanceof URL) return fileURLToPath(value);
  if (typeof value === 'string' && value.length > 0) return resolve(value);
  throw new Error(`${name} must be a non-empty path`);
}

function isPlainObject(value) {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

function readJson(api, path, label) {
  let body;
  try {
    body = api.readFileSync(path, 'utf8');
  } catch (error) {
    if (error?.code === 'ENOENT') return null;
    throw error;
  }
  try {
    return JSON.parse(body);
  } catch (error) {
    const wrapped = new Error(`${label} is not valid JSON`);
    wrapped.cause = error;
    throw wrapped;
  }
}

function insideOrEqual(root, target) {
  const rel = relative(root, target);
  return rel === '' || (rel !== '..' && !rel.startsWith(`..${sep}`) && !isAbsolute(rel));
}

function assertInside(root, target, label) {
  if (!insideOrEqual(root, target)) throw new Error(`${label} escapes its directory`);
  return target;
}

function extensionOf(file) {
  const match = /\.([A-Za-z0-9]+)$/.exec(typeof file === 'string' ? file : '');
  return match ? match[1].toLowerCase() : 'bin';
}

function fileList(root, api) {
  const files = [];
  if (!api.existsSync(root)) return files;
  const pending = [root];
  while (pending.length > 0) {
    const directory = pending.pop();
    const entries = api.readdirSync(directory);
    for (const entry of entries) {
      const name = typeof entry === 'string' ? entry : entry.name;
      const path = join(directory, name);
      if (typeof entry === 'object' && typeof entry.isSymbolicLink === 'function' && entry.isSymbolicLink()) continue;
      const isDirectory = typeof entry === 'object' && typeof entry.isDirectory === 'function'
        ? entry.isDirectory()
        : api.statSync(path).isDirectory();
      if (isDirectory) pending.push(path);
      else files.push(path);
    }
  }
  return files.sort();
}

function ensureParent(api, path) {
  api.mkdirSync(dirname(path), { recursive: true });
}

function writeBytes(api, path, bytes) {
  ensureParent(api, path);
  api.writeFileSync(path, bytes);
}

function writeIfAbsent(api, path, bytes, label, changes) {
  if (api.existsSync(path)) {
    changes.skipped.push(label);
    return false;
  }
  writeBytes(api, path, bytes);
  changes.written.push(label);
  return true;
}

function copyTreeIfAbsent(api, sourceRoot, destinationRoot, label, changes, rootForSafety) {
  for (const source of fileList(sourceRoot, api)) {
    const rel = relative(sourceRoot, source);
    const destination = assertInside(rootForSafety, join(destinationRoot, rel), `${label} media`);
    writeIfAbsent(api, destination, api.readFileSync(source), `${label}:${rel.replaceAll(sep, '/')}`, changes);
  }
}

function mediaBytes(entry) {
  if (entry.kind === 'clip' || entry.kind === 'video') return renderClipSvg(entry);
  return renderStill(entry.motif, entry.width, entry.height);
}

function mediaDestinations(entry, { runtimeDir, packageRoot }) {
  if (entry.group === 'reference') return [];
  return [entry.file, entry.fallbackFile]
    .filter(Boolean)
    .map(rel => entry.group === 'character' ? join(runtimeDir, rel) : join(packageRoot, rel));
}

function ensureExampleMedia(exampleRoot, api, changes, targets) {
  for (const entry of MEDIA) {
    if (entry.group === 'reference') {
      if (!targets.references) continue;
    } else if (mediaDestinations(entry, targets).some(candidate => api.existsSync(candidate))) {
      continue;
    }
    const candidates = [entry.file, entry.fallbackFile].filter(Boolean);
    if (candidates.some(candidate => api.existsSync(join(exampleRoot, candidate)))) continue;
    const target = join(exampleRoot, (entry.kind === 'clip' || entry.kind === 'video') && entry.fallbackFile
      ? entry.fallbackFile
      : entry.file);
    writeBytes(api, target, mediaBytes(entry));
    changes.generated.push(relative(exampleRoot, target).replaceAll(sep, '/'));
  }
  for (const track of TRACKS) {
    const destination = join(targets.packagesRoot, 'assets', track.file);
    if (api.existsSync(destination)) continue;
    const target = join(exampleRoot, 'assets', track.file);
    if (api.existsSync(target)) continue;
    writeBytes(api, target, renderTrack(track.id));
    changes.generated.push(relative(exampleRoot, target).replaceAll(sep, '/'));
  }
}

function referenceSourcePath(exampleRoot, reference, api) {
  const referencesRoot = join(exampleRoot, 'references');
  const label = typeof reference.label === 'string' ? reference.label.replaceAll('\\', '/').split('/').pop() : '';
  if (!label) return null;
  const direct = join(referencesRoot, label);
  if (api.existsSync(direct)) return direct;
  const stem = label.replace(/\.[A-Za-z0-9]+$/, '');
  const extension = extensionOf(label);
  const alternatives = [extension, 'mp4', 'mov', 'webm', 'png', 'jpg', 'jpeg', 'webp', 'gif', 'svg'];
  for (const candidate of new Set(alternatives)) {
    if (!candidate || candidate === 'bin') continue;
    const path = join(referencesRoot, `${stem}.${candidate}`);
    if (api.existsSync(path)) return path;
  }
  return null;
}

function findExistingReferenceFile(filesDir, id, api) {
  if (!api.existsSync(filesDir)) return null;
  for (const entry of api.readdirSync(filesDir)) {
    const name = typeof entry === 'string' ? entry : entry.name;
    if (name === id || name.startsWith(`${id}.`)) return join(filesDir, name);
  }
  return null;
}

function normalizeFrames(frames) {
  if (!Array.isArray(frames)) return [];
  return frames
    .filter(frame => isPlainObject(frame)
      && Number.isInteger(frame.index) && frame.index >= 0
      && typeof frame.atSec === 'number' && Number.isFinite(frame.atSec) && frame.atSec >= 0)
    .map(frame => ({ index: frame.index, atSec: frame.atSec }))
    .sort((a, b) => a.index - b.index);
}

function buildReferenceLibrary({ manifest, exampleRoot, referencesRoot, chatId, api, changes, clock }) {
  const filesDir = join(referencesRoot, 'files');
  const createdAt = typeof manifest.createdAt === 'string' && Number.isFinite(Date.parse(manifest.createdAt))
    ? manifest.createdAt
    : new Date(clock()).toISOString();
  const references = [];
  const assignments = [];

  for (const reference of Array.isArray(manifest.references) ? manifest.references : []) {
    if (!isPlainObject(reference) || typeof reference.id !== 'string' || !/^ref_[0-9a-f]{16}$/.test(reference.id)) continue;
    const label = typeof reference.label === 'string' ? reference.label : 'reference';
    const source = referenceSourcePath(exampleRoot, reference, api);
    let storedFile = null;
    let bytes = null;
    if (source) {
      const extension = extensionOf(source);
      storedFile = `${reference.id}.${extension}`;
      const destination = assertInside(referencesRoot, join(filesDir, storedFile), 'reference media');
      if (api.existsSync(destination)) {
        changes.skipped.push(`reference:${reference.id}`);
        bytes = api.readFileSync(destination);
      } else {
        bytes = api.readFileSync(source);
        writeBytes(api, destination, bytes);
        changes.written.push(`reference:${reference.id}`);
      }
    } else {
      const existing = findExistingReferenceFile(filesDir, reference.id, api);
      if (existing) {
        storedFile = relative(filesDir, existing).replaceAll(sep, '/');
        bytes = api.readFileSync(existing);
        changes.skipped.push(`reference:${reference.id}`);
      }
    }

    const fallbackExtension = extensionOf(label);
    const record = {
      id: reference.id,
      kind: typeof reference.kind === 'string' ? reference.kind : 'image',
      mime: MIME_BY_EXT[extensionOf(storedFile ?? label)] ?? 'application/octet-stream',
      file: storedFile ?? `${reference.id}.${fallbackExtension}`,
      width: Number.isInteger(reference.width) && reference.width > 0 ? reference.width : 1,
      height: Number.isInteger(reference.height) && reference.height > 0 ? reference.height : 1,
      role: typeof reference.role === 'string' && reference.role ? reference.role : 'other',
      note: typeof reference.note === 'string' ? reference.note : '',
      label,
      frames: normalizeFrames(reference.frames),
      ext: extensionOf(storedFile ?? label),
      createdAt,
      updatedAt: createdAt,
      revision: 1,
    };
    if (bytes) {
      record.bytes = bytes.length;
      record.sha256 = createHashHex(bytes);
    }
    if (typeof reference.durationSec === 'number' && Number.isFinite(reference.durationSec) && reference.durationSec >= 0) {
      record.durationSec = reference.durationSec;
    }
    references.push(record);

    for (const assignment of Array.isArray(reference.assignedTo) ? reference.assignedTo : []) {
      if (!isPlainObject(assignment) || typeof assignment.sceneId !== 'string' || typeof assignment.slot !== 'string') continue;
      assignments.push({ refId: reference.id, sceneId: assignment.sceneId, slot: assignment.slot });
    }
  }

  return {
    schema: 'comfyrizz.reference-library/v1',
    chatId,
    revision: 1,
    updatedAt: createdAt,
    references,
    assignments,
  };
}

function createHashHex(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

/**
 * Seed the demo package and its sidecars into `runtimeDir`.
 *
 * @param {{
 *   runtimeDir: string,
 *   exampleDir: string,
 *   fs?: object,
 *   chatId?: string,
 *   clock?: () => Date|string|number,
 *   generateMedia?: boolean,
 * }} options
 * @returns {{
 *   packageId: string,
 *   chatId: string,
 *   changed: boolean,
 *   noop: boolean,
 *   written: string[],
 *   skipped: string[],
 *   generated: string[],
 *   paths: object,
 * }}
 */
export function seedDemoProject(options = {}) {
  if (!isPlainObject(options)) throw new Error('seedDemoProject options must be an object');
  const runtimeDir = toPath(options.runtimeDir, 'runtimeDir');
  const exampleDir = toPath(options.exampleDir, 'exampleDir');
  const api = { ...nodeFs, ...(isPlainObject(options.fs) ? options.fs : {}) };
  const chatId = options.chatId ?? DEMO_CHAT_ID;
  if (typeof chatId !== 'string' || !CHAT_ID_RE.test(chatId)) throw new Error('invalid chat id');
  const clock = typeof options.clock === 'function' ? options.clock : () => new Date();
  const generateMedia = options.generateMedia !== false;
  const changes = { written: [], skipped: [], generated: [] };

  if (typeof api.existsSync !== 'function' || typeof api.readFileSync !== 'function'
    || typeof api.writeFileSync !== 'function' || typeof api.mkdirSync !== 'function') {
    throw new Error('seedDemoProject needs an fs with existsSync, readFileSync, writeFileSync and mkdirSync');
  }
  const packageSource = join(exampleDir, 'package.json');
  const packageBytes = api.readFileSync(packageSource, 'utf8');
  let pkg;
  try {
    pkg = JSON.parse(packageBytes);
  } catch (error) {
    const wrapped = new Error('example package.json is not valid JSON');
    wrapped.cause = error;
    throw wrapped;
  }
  if (!isPlainObject(pkg) || typeof pkg.id !== 'string' || !PACKAGE_ID_RE.test(pkg.id)) {
    throw new Error('example package.json has an invalid id');
  }
  const validation = validatePackage(pkg);
  if (!validation.valid) {
    const error = new Error('example package is invalid');
    error.errors = validation.errors;
    throw error;
  }

  const packagesRoot = join(runtimeDir, 'packages');
  const packageTarget = join(packagesRoot, `${pkg.id}.json`);
  const packageRoot = join(packagesRoot, pkg.id);
  const manifestSource = join(exampleDir, 'references', 'manifest.json');
  const referencesRoot = join(runtimeDir, 'references', chatId);
  const libraryPath = join(referencesRoot, 'refs.json');
  const needsReferences = api.existsSync(manifestSource) && !api.existsSync(libraryPath);

  writeIfAbsent(api, packageTarget, packageBytes, 'package', changes);
  if (generateMedia) {
    ensureExampleMedia(exampleDir, api, changes, { runtimeDir, packagesRoot, packageRoot, references: needsReferences });
  }

  copyTreeIfAbsent(api, join(exampleDir, 'assets'), join(packagesRoot, 'assets'), 'asset', changes, packagesRoot);
  copyTreeIfAbsent(api, join(exampleDir, 'takes'), join(packageRoot, 'takes'), 'take', changes, packagesRoot);

  const takesSource = join(exampleDir, 'takes.json');
  if (api.existsSync(takesSource)) {
    const takes = readJson(api, takesSource, 'takes.json');
    if (isPlainObject(takes) && takes.packageId !== undefined && takes.packageId !== pkg.id) {
      throw new Error('takes.json packageId does not match package.json');
    }
    writeIfAbsent(api, join(runtimeDir, 'takes', `${pkg.id}.json`), api.readFileSync(takesSource), 'takes', changes);
  }

  const editorSource = join(exampleDir, 'editor.json');
  if (api.existsSync(editorSource)) {
    writeIfAbsent(api, join(runtimeDir, 'editor', `${pkg.id}.json`), api.readFileSync(editorSource), 'editor', changes);
  }

  copyTreeIfAbsent(api, join(exampleDir, 'characters'), join(runtimeDir, 'characters'), 'character', changes, runtimeDir);

  if (api.existsSync(manifestSource)) {
    const manifestBytes = api.readFileSync(manifestSource);
    const manifest = readJson(api, manifestSource, 'reference manifest');
    if (!isPlainObject(manifest)) throw new Error('reference manifest must be an object');
    writeIfAbsent(api, join(referencesRoot, 'manifest.json'), manifestBytes, 'references:manifest', changes);
    writeIfAbsent(api, join(runtimeDir, 'references', 'manifest.json'), manifestBytes, 'references:manifest-root', changes);
    if (!api.existsSync(libraryPath)) {
      const library = buildReferenceLibrary({ manifest, exampleRoot: exampleDir, referencesRoot, chatId, api, changes, clock });
      writeBytes(api, libraryPath, `${JSON.stringify(library, null, 2)}\n`);
      changes.written.push('references');
    } else {
      changes.skipped.push('references');
    }
  }

  return {
    packageId: pkg.id,
    chatId,
    changed: changes.written.length > 0,
    noop: changes.written.length === 0,
    written: changes.written.slice(),
    skipped: changes.skipped.slice(),
    generated: changes.generated.slice(),
    paths: {
      package: packageTarget,
      packages: packagesRoot,
      packageRoot,
      takes: join(runtimeDir, 'takes', `${pkg.id}.json`),
      editor: join(runtimeDir, 'editor', `${pkg.id}.json`),
      references: referencesRoot,
    },
  };
}

export default seedDemoProject;
