import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { adoptProductWalkthroughAttachments } from '../src/product-walkthrough.mjs';
import { createReferenceStore } from '../src/references/store.mjs';
import { validatePackage } from '../../../packages/schema/src/index.mjs';
import { renderPackage } from '../../renderer/scripts/render-package-lib.mjs';

test('Custom renders the authorized original image and leaves a reference-only upload untouched', { timeout: 300_000 }, async t => {
  mkdirSync('/tmp/opencode', { recursive: true });
  const root = mkdtempSync(join(tmpdir(), 'custom-editorial-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const plate = join(root, 'plate.png');
  const make = spawnSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'color=c=red:s=128x128', '-frames:v', '1', '-threads', '1', plate]);
  assert.equal(make.status, 0, String(make.stderr));
  const store = createReferenceStore({ rootDir: root, chatId: 'chat_custom_editorial' });
  const selected = store.add({ bytes: readFileSync(plate), filename: 'plate.png' });
  const blue = join(root, 'blue.png');
  const makeBlue = spawnSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'color=c=blue:s=128x128', '-frames:v', '1', '-threads', '1', blue]);
  assert.equal(makeBlue.status, 0, String(makeBlue.stderr));
  const ignored = store.add({ bytes: readFileSync(blue), filename: 'ignored.png' });
  const pkg = JSON.parse(readFileSync(new URL('../../renderer/test/fixtures/tiny/package.json', import.meta.url)));
  pkg.scenes = [{ id: 's1', layout: 'hero', variant: 'full-bleed', preferredFrames: 30, copy: { headline: '.' }, background: { procedural: { pattern: 'gradient', palette: ['#000000', '#000000'] } } }];
  pkg.assets = {};
  pkg.datasets = {};
  const options = { runtimeDir: root, conversationId: 'chat_custom_editorial', package: pkg, imagesOnly: true };
  const noSelection = await adoptProductWalkthroughAttachments(options);
  assert.equal(noSelection.package, pkg);
  store.update(selected.id, { usage: 'editorial', editorialScope: 'custom' });
  const result = await adoptProductWalkthroughAttachments(options);
  assert.deepEqual(result.skipped, []);
  assert.equal(result.adopted.length, 1);
  const asset = result.package.assets[result.adopted[0].assetId];
  assert.equal(asset.source.id, selected.id);
  assert.notEqual(asset.source.id, ignored.id);
  assert.deepEqual(asset.license, { id: 'User-Upload', approved_by_user: true });
  assert.equal(asset.redistributable, false);
  assert.deepEqual(readFileSync(join(root, 'packages', asset.file)), readFileSync(plate));
  assert.equal(validatePackage(result.package).valid, true, JSON.stringify(validatePackage(result.package).errors));
  const packagePath = join(root, 'packages', 'package.json');
  writeFileSync(packagePath, JSON.stringify(result.package));
  const still = join(root, 'still.png');
  renderPackage(packagePath, still, { still: true, frame: 15, normalizeLoudness: false });
  const pixels = spawnSync('ffmpeg', ['-v', 'error', '-i', still, '-frames:v', '1', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-'], { maxBuffer: 4 * 1024 * 1024 });
  assert.equal(pixels.status, 0, String(pixels.stderr));
  let red = 0;
  for (let i = 0; i < pixels.stdout.length; i += 3) if (pixels.stdout[i] > 180 && pixels.stdout[i + 1] < 60 && pixels.stdout[i + 2] < 60) red++;
  assert.ok(red > 1000, `expected the red original plate to be visibly rendered, got ${red} pixels`);
});
