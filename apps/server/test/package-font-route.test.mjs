import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createApp } from '../src/app.mjs';

test('package font endpoint requires authentication, declared TTF, and contained regular bytes', async t => {
  const root = mkdtempSync(join(tmpdir(), 'package-font-route-'));
  const token = 'package-font-test-token';
  const app = createApp({ token, runtimeDir: root });
  const server = createServer(app.handler);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await app.close(); rmSync(root, { recursive: true, force: true }); });
  const pkg = JSON.parse(readFileSync(new URL('../../../packages/schema/fixtures/valid/minimal.json', import.meta.url)));
  pkg.theme.fonts = [{ family: 'TestFont', file: 'assets/test.ttf' }];
  app.store.write(pkg);
  const assets = join(root, 'packages', 'assets'); mkdirSync(assets, { recursive: true });
  const font = readFileSync(new URL('../../renderer/public/fonts/Inter-Variable.ttf', import.meta.url));
  writeFileSync(join(assets, 'test.ttf'), font);
  writeFileSync(join(assets, 'secret.ttf'), font);
  const url = `http://127.0.0.1:${server.address().port}/api/package/${pkg.id}/font`;
  const get = (path, headers = { 'x-comfyrizz-token': token }, method = 'GET') => fetch(`${url}?path=${encodeURIComponent(path)}`, { headers, method });
  assert.equal((await get('assets/test.ttf', {})).status, 401);
  assert.equal((await get('assets/test.ttf', { 'x-comfyrizz-token': 'wrong' })).status, 401);
  assert.equal((await fetch(`${url}?path=assets%2Ftest.ttf&token=${token}`)).status, 401);
  const response = await get('assets/test.ttf');
  assert.equal(response.status, 200); assert.equal(response.headers.get('content-type'), 'font/ttf');
  assert.equal(response.headers.get('x-content-type-options'), 'nosniff');
  assert.deepEqual(Buffer.from(await response.arrayBuffer()), font);
  assert.equal((await get('assets/test.ttf', undefined, 'HEAD')).status, 200);
  assert.equal((await get('assets/secret.ttf')).status, 404);
  assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/api/package/missing/font?path=assets%2Ftest.ttf`, { headers: { 'x-comfyrizz-token': token } })).status, 404);
  assert.equal((await get('../secret.ttf')).status, 404);
  assert.equal((await get('assets/test.ttf', { 'x-comfyrizz-token': token, origin: `http://127.0.0.1:${server.address().port}` }, 'POST')).status, 405);
  rmSync(join(assets, 'test.ttf')); symlinkSync(join(assets, 'secret.ttf'), join(assets, 'test.ttf'));
  assert.equal((await get('assets/test.ttf')).status, 404);
  rmSync(join(assets, 'test.ttf')); writeFileSync(join(assets, 'test.ttf'), 'not a font');
  assert.equal((await get('assets/test.ttf')).status, 404);
});
