// Regenerates src/workflow-manifest.ts from the repo's workflow graphs.
//
// The agent plans image/video assets before any GPU job exists, and the jobs
// planner requires `gen.workflow_sha256` so a job can be cached and audited.
// Reading the graphs at plan time would depend on the process cwd, so the
// hashes are generated here and committed; the parity test recomputes them.
//
//   node scripts/workflow-manifest.mjs
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const workflowsDir = join(here, '..', '..', '..', 'workflows');
const outFile = join(here, '..', 'src', 'workflow-manifest.ts');

const files = readdirSync(workflowsDir)
  .filter(name => name.endsWith('.api.json'))
  .sort();

const lines = files.map(name => {
  const sha = createHash('sha256').update(readFileSync(join(workflowsDir, name))).digest('hex');
  return `  'workflows/${name}': '${sha}',`;
});

const body = [
  '// Generated by scripts/workflow-manifest.mjs; do not edit by hand.',
  '// sha256 of each committed workflow graph, keyed by the package-relative',
  '// `gen.workflow` path, so the agent can stamp `gen.workflow_sha256`.',
  'export const WORKFLOW_SHA256: Record<string, string> = {',
  ...lines,
  '};',
  '',
].join('\n');

writeFileSync(outFile, body);
process.stdout.write(`wrote ${files.length} workflow hashes to ${outFile}\n`);
